export const hasOrigin = (char: string) => Boolean(ORIGINS[char])

/** 一筆描多久、筆跟筆之間停多久（毫秒）：整張圖大約一秒半畫完 */
export function strokeTiming(count: number) {
  const each = Math.max(160, Math.min(500, 1400 / Math.max(count, 1)))
  return Array.from({ length: count }, (_, i) => ({ delay: Math.round(i * each), dur: Math.round(each * 0.9) }))
}

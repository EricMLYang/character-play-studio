export const radicalById = (id) => RADICALS.find((r) => r.id === id)

/** 這個字住在哪一家（一個字只住一家）；不在表裡回 undefined */
export const familyOf = (char) => RADICALS.find((r) => Object.hasOwn(r.members, char))

/** 部首家族固定會唸的句子 */
export const RADICAL_LINES = {
  ask: (r) => `哪一個字有${r.name}？`,
  home: (r) => `${r.name}的家`,
}
export const RADICAL_FIXED = {
  hello: '每個部首都有一個家，點一個家進去看看！',
  play: '來找找看，誰是這一家的？',
  allFound: '家人都找到了！',
  nameHome: '你的名字，住在三個部首家族裡！',
}

/** 要先做成音檔的所有句子 */
export function radicalLines() {
  return [
    ...Object.values(RADICAL_FIXED),
    ...RADICALS.flatMap((r) => [r.intro, r.change, r.common, r.name, RADICAL_LINES.ask(r), RADICAL_LINES.home(r), ...Object.values(r.members)]),
  ]
}

/** 部首的樣子也要有筆順檔（家族的門牌要一筆一筆寫出來） */
export const radicalGlyphs = () => [...new Set(RADICALS.flatMap((r) => r.forms))]
